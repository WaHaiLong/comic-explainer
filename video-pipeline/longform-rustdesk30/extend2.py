def apply_extend2(chapters):
    for ch in chapters:
        n = int(ch["num"])
        for pi, p in enumerate(ch["panels"]):
            if pi == 0 or p.get("type") == "terminal_card":
                continue
            key = (n, pi)
            if key in EXTEND2:
                v = EXTEND2[key]
                p["lines"] = p["lines"] + (v if isinstance(v, list) else [v])
    return chapters
