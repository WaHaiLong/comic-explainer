def apply_extend(chapters):
    for ch in chapters:
        n = int(ch["num"])
        for pi, p in enumerate(ch["panels"]):
            key = (n, pi)
            if key not in EXTEND or p.get("type") == "terminal_card":
                continue
            val = EXTEND[key]
            if isinstance(val, list):      # 章头卡两句
                p["lines"] = p["lines"] + val
            else:
                p["lines"] = p["lines"] + [val]
    return chapters
